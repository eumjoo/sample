import { build } from 'esbuild';
import { writeFile, mkdir, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { diagramMarkup } from '../src/diagram.js';
import { createLayout } from '../src/layout.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/main.js'],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  outfile: 'standalone.js',
  minify: true,
  legalComments: 'none',
  write: false,
});
const escapeClosingTags = value => value.replace(/<\/(script|style)/gi, '<\\/$1');
const js = result.outputFiles.find(file => file.path.endsWith('.js')).text;
const css = result.outputFiles.find(file => file.path.endsWith('.css')).text;
const license = await readFile(new URL('../node_modules/three/LICENSE', import.meta.url), 'utf8');
const staticDiagram = diagramMarkup.replace(/id="([^"]+)"/g, 'id="static-$1"').replace(/url\(#/g, 'url(#static-');
const html = `<!doctype html>
<!-- Generated by npm run build: edit src/, not this bundled file. -->
<html lang="ko"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="theme-color" content="#101e2c"><title>NEPHRON LAB · 네프론 탐구 실험실</title>
<style>${escapeClosingTags(css)}
html:not([data-app-ready="true"]) #app button,html:not([data-app-ready="true"]) #app select{pointer-events:none;opacity:.65}
#boot-fallback{max-width:900px;margin:36px auto;padding:24px}#boot-fallback h1{font-size:28px}#boot-fallback svg{max-height:480px;width:100%}#boot-fallback table{border-collapse:collapse;width:100%;font-size:13px}#boot-fallback th,#boot-fallback td{padding:12px;text-align:left;border-bottom:1px solid #344858}#boot-fallback p{color:#a5bec9;line-height:1.8}#boot-fallback details{margin-top:20px;font-size:11px;color:#7897a4}
</style></head><body>
<section id="boot-fallback" hidden><div class="eyebrow">NEPHRON LAB</div><h1>네프론에서 물질은 어디로 갈까요?</h1><p id="startup-status" role="status">혈액에서 작은 물질이 여과되고, 필요한 물질은 다시 혈액으로 돌아갑니다.</p>${staticDiagram}
<table><thead><tr><th>물질</th><th>이동 경로</th></tr></thead><tbody><tr><td>혈구 · 단백질</td><td>혈관 안에 남음</td></tr><tr><td>포도당 · 아미노산</td><td>여과 → 세뇨관에서 재흡수 → 혈액</td></tr><tr><td>물</td><td>여과 → 대부분 재흡수 → 일부 소변으로 배출</td></tr><tr><td>요소</td><td>여과·분비 → 오줌으로 배출</td></tr></tbody></table>
<p>수분 부족: 물을 더 많이 재흡수하여 소변량 감소<br>물 마신 후: 물의 재흡수가 줄어 소변량 증가</p>
<noscript><p>현재 정적 그림을 보고 있습니다. JavaScript를 허용하면 상황 선택과 움직이는 입자를 사용할 수 있습니다.</p></noscript>
<details><summary>오픈 소스 라이선스</summary><pre>${license.replaceAll('&','&amp;').replaceAll('<','&lt;')}</pre></details></section>
<noscript><p style="padding:16px;text-align:center;color:#a5bec9">네프론 그림을 표시하고 있습니다. 상황 선택과 움직이는 입자는 JavaScript를 허용하면 사용할 수 있습니다.</p></noscript>
<div id="app">${createLayout()}</div>
<script>try {\n${escapeClosingTags(js)}\n} catch(error) { document.documentElement.removeAttribute('data-app-ready'); document.getElementById('app').hidden=true;document.getElementById('boot-fallback').hidden=false; document.getElementById('startup-status').textContent='애니메이션을 시작할 수 없어 네프론 그림을 표시합니다. 아래 표에서 물질의 이동을 확인하세요.'; console.error(error); }</script>
</body></html>`;
// Bundled GLSL template strings contain insignificant line-end spaces.
const output = html.replace(/[\t ]+$/gm, '');
await writeFile(new URL('../index.html', import.meta.url), output);
await mkdir(new URL('../dist/', import.meta.url), { recursive: true });
await writeFile(new URL('../dist/standalone.html', import.meta.url), output);
await writeFile(new URL('../dist/.nojekyll', import.meta.url), '');
console.log('Created index.html and dist/standalone.html: one HTML file with inline SVG, CSS and JavaScript.');
